import type { AstNode } from 'langium';
import { AbstractSemanticTokenProvider } from 'langium/lsp';
import type { SemanticTokenAcceptor } from 'langium/lsp';
import { SemanticTokenTypes } from 'vscode-languageserver';
import {
    isAttribute, isCardinality, isClassDeclaration, isDatatype, isEnumeration, isEnumLiteral,
    isExternalRelation, isGeneralizationSet, isImport, isLanguageText, isPackage, isRelation,
    isRelationEndMetaAttributes, isOntology, isBundleEntry
} from '../generated/ast.js';

/**
 * Classifies identifiers so an editor can color them by meaning rather than
 * by the single flat keyword rule the generated TextMate grammar provides.
 *
 * The TextMate grammar (auto-generated by `langium-cli`) only knows keywords,
 * strings and comments, so without this every class name, relation name,
 * cardinality and role name renders identically.
 */
export class TontoSemanticTokenProvider extends AbstractSemanticTokenProvider {

    protected highlightElement(node: AstNode, acceptor: SemanticTokenAcceptor): void {
        if (isPackage(node) || isOntology(node) || isBundleEntry(node)) {
            acceptor({ node, property: 'name', type: SemanticTokenTypes.namespace, modifier: ['declaration'] });
            return;
        }

        if (isImport(node)) {
            if (node.package) acceptor({ node, property: 'package', type: SemanticTokenTypes.namespace });
            if (node.alias) {
                acceptor({ node, property: 'alias', type: SemanticTokenTypes.namespace, modifier: ['declaration'] });
            }
            return;
        }

        if (isClassDeclaration(node)) {
            // The stereotype is the load-bearing word in OntoUML, so give it
            // its own token type rather than leaving it as a plain keyword.
            acceptor({ node, property: 'stereotype', type: SemanticTokenTypes.keyword });
            acceptor({ node, property: 'name', type: SemanticTokenTypes.class, modifier: ['declaration'] });
            node.natures.forEach((_, index) =>
                acceptor({ node, property: 'natures', index, type: SemanticTokenTypes.enumMember }));
            node.specializes.forEach((_, index) =>
                acceptor({ node, property: 'specializes', index, type: SemanticTokenTypes.class }));
            if (node.instanceOf) {
                acceptor({ node, property: 'instanceOf', type: SemanticTokenTypes.class });
            }
            // A relation is colored as relations are where they are named;
            // an event type as a class.
            node.derivedFrom.forEach((reference, index) =>
                acceptor({ node, property: 'derivedFrom', index,
                    type: isRelation(reference.ref) ? SemanticTokenTypes.method : SemanticTokenTypes.class }));
            return;
        }

        if (isDatatype(node) || isEnumeration(node)) {
            acceptor({ node, property: 'name', type: SemanticTokenTypes.type, modifier: ['declaration'] });
            node.specializes.forEach((_, index) =>
                acceptor({ node, property: 'specializes', index, type: SemanticTokenTypes.type }));
            return;
        }

        if (isEnumLiteral(node)) {
            acceptor({ node, property: 'name', type: SemanticTokenTypes.enumMember, modifier: ['declaration'] });
            return;
        }

        if (isAttribute(node)) {
            // Same token as a relation stereotype: both are the word after `@`.
            node.stereotypes.forEach((_, index) =>
                acceptor({ node, property: 'stereotypes', index, type: SemanticTokenTypes.decorator }));
            acceptor({ node, property: 'name', type: SemanticTokenTypes.property, modifier: ['declaration'] });
            acceptor({ node, property: 'type', type: SemanticTokenTypes.type });
            return;
        }

        if (isRelation(node)) {
            if (node.stereotype) {
                acceptor({ node, property: 'stereotype', type: SemanticTokenTypes.decorator });
            }
            if (node.name) {
                acceptor({ node, property: 'name', type: SemanticTokenTypes.method, modifier: ['declaration'] });
            }
            if (isExternalRelation(node)) {
                acceptor({ node, property: 'source', type: SemanticTokenTypes.class });
            }
            acceptor({ node, property: 'target', type: SemanticTokenTypes.class });
            if (node.specializes) {
                acceptor({ node, property: 'specializes', type: SemanticTokenTypes.method });
            }
            if (node.inverseOf) {
                acceptor({ node, property: 'inverseOf', type: SemanticTokenTypes.method });
            }
            node.derivedFrom.forEach((_, index) =>
                acceptor({ node, property: 'derivedFrom', index, type: SemanticTokenTypes.class }));
            return;
        }

        if (isRelationEndMetaAttributes(node)) {
            if (node.name) {
                acceptor({ node, property: 'name', type: SemanticTokenTypes.parameter, modifier: ['declaration'] });
            }
            if (node.subsets) {
                acceptor({ node, property: 'subsets', type: SemanticTokenTypes.parameter });
            }
            if (node.redefines) {
                acceptor({ node, property: 'redefines', type: SemanticTokenTypes.parameter });
            }
            return;
        }

        if (isGeneralizationSet(node)) {
            acceptor({ node, property: 'name', type: SemanticTokenTypes.type, modifier: ['declaration'] });
            acceptor({ node, property: 'general', type: SemanticTokenTypes.class });
            node.specifics.forEach((_, index) =>
                acceptor({ node, property: 'specifics', index, type: SemanticTokenTypes.class }));
            node.categorizers.forEach((_, index) =>
                acceptor({ node, property: 'categorizers', index, type: SemanticTokenTypes.class }));
            return;
        }

        if (isCardinality(node)) {
            acceptor({ node, property: 'lowerBound', type: SemanticTokenTypes.number });
            if (node.upperBound !== undefined) {
                acceptor({ node, property: 'upperBound', type: SemanticTokenTypes.number });
            }
            return;
        }

        if (isLanguageText(node)) {
            acceptor({ node, property: 'language', type: SemanticTokenTypes.enumMember });
            acceptor({ node, property: 'text', type: SemanticTokenTypes.string });
        }
    }
}
